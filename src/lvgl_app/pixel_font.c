static const PixelFontDsc dsc112 = {14};

#define PIXEL_FONT(name, scale, descriptor)       \
  const lv_font_t name = {                        \
      .get_glyph_dsc = pixel_get_glyph_dsc,       \
      .get_glyph_bitmap = pixel_get_glyph_bitmap, \
      .line_height = 8 * (scale),                  \
      .base_line = (scale),                        \
      .subpx = LV_FONT_SUBPX_NONE,                 \
      .underline_position = -(scale),              \
      .underline_thickness = (scale),              \
      .dsc = &(descriptor),                        \
      .fallback = NULL,                            \
  }

