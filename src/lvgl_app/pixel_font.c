typedef struct {
  uint8_t scale;
} PixelFontDsc;

// Widest glyph in use is 5*14 x 7*14, which packs into 858 bytes at 1 bpp.
static uint8_t bitmap_buffer[858];

static uint8_t normalize_char(uint32_t c) {
  if (c >= 'a' && c <= 'z') return (uint8_t)(c - 'a' + 'A');
  switch (c) {
    case 0x00C4: case 0x00C5: case 0x00C0: case 0x00C1: case 0x00C2:
    case 0x00E4: case 0x00E5: case 0x00E0: case 0x00E1: case 0x00E2: return 'A';
    case 0x00D6: case 0x00D2: case 0x00D3: case 0x00D4:
    case 0x00F6: case 0x00F2: case 0x00F3: case 0x00F4: case 0x03A9: return 'O';
    case 0x00DC: case 0x00D9: case 0x00DA: case 0x00DB:
    case 0x00FC: case 0x00F9: case 0x00FA: case 0x00FB: return 'U';
    case 0x00C9: case 0x00C8: case 0x00CA: case 0x00CB:
    case 0x00E9: case 0x00E8: case 0x00EA: case 0x00EB: return 'E';
    case 0x00CD: case 0x00CC: case 0x00CE: case 0x00CF:
    case 0x00ED: case 0x00EC: case 0x00EE: case 0x00EF: return 'I';
    case 0x00D1: case 0x00F1: return 'N';
    case 0x00C7: case 0x00E7: return 'C';
    case 0x00DF: return 'B';
    case 0x00B0: return 0xB0;
    default: return c < 128 ? (uint8_t)c : '?';
  }
}

static const uint8_t *glyph_rows(uint32_t letter) {
  const uint8_t c = normalize_char(letter);
  for (uint32_t i = 0; i < sizeof(glyphs) / sizeof(glyphs[0]); i++) {
    if (glyphs[i].ch == c) return glyphs[i].row;
  }
  for (uint32_t i = 0; i < sizeof(glyphs) / sizeof(glyphs[0]); i++) {
    if (glyphs[i].ch == '?') return glyphs[i].row;
  }
  return NULL;
}

static bool pixel_get_glyph_dsc(const lv_font_t *font, lv_font_glyph_dsc_t *out, uint32_t letter,
                                uint32_t letter_next) {
  (void)letter_next;
  const PixelFontDsc *dsc = (const PixelFontDsc *)font->dsc;
  const uint8_t scale = dsc->scale;
  memset(out, 0, sizeof(*out));
  // The period carries half an advance: decimal readouts read as one number
  // rather than two, and a four-character value buys back a whole cell of room.
  // Its box stays 5 cells wide, but the empty columns are transparent at 1 bpp.
  out->adv_w = (letter == ' ' || letter == '.') ? 3 * scale : 6 * scale;
  if (letter != ' ') {
    out->box_w = 5 * scale;
    out->box_h = 7 * scale;
    out->bpp = 1;
  }
  return true;
}

static const uint8_t *pixel_get_glyph_bitmap(const lv_font_t *font, uint32_t letter) {
  if (letter == ' ') return NULL;
  const PixelFontDsc *dsc = (const PixelFontDsc *)font->dsc;
  const uint8_t scale = dsc->scale;
  const uint8_t *rows = glyph_rows(letter);
  if (!rows) return NULL;
  const uint16_t w = 5 * scale;
  const uint16_t h = 7 * scale;
  const uint16_t bytes = (uint16_t)((w * h + 7) / 8);
  memset(bitmap_buffer, 0, bytes);
  for (uint8_t sy = 0; sy < 7; sy++) {
    for (uint8_t sx = 0; sx < 5; sx++) {
      if ((rows[sy] & (0x10 >> sx)) == 0) continue;
      for (uint8_t yy = 0; yy < scale; yy++) {
        for (uint8_t xx = 0; xx < scale; xx++) {
          const uint32_t bit = (uint32_t)(sy * scale + yy) * w + sx * scale + xx;
          bitmap_buffer[bit >> 3] |= (uint8_t)(0x80 >> (bit & 7));
        }
      }
    }
  }
  return bitmap_buffer;
}

